const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const serve = require('./preview.cjs');
const base='http://127.0.0.1:8790/hoea_to_waka/';
const guide=base+'about/brand-guidelines/#colours';
const cssColour=(page,selector,property='backgroundColor')=>page.locator(selector).first().evaluate((el,p)=>getComputedStyle(el)[p],property);

(async()=>{
  const {defaults,brandStorageKey,contrast}=await import('../design/brand-tokens.mjs');
  const server=serve(8790),browser=await chromium.launch({channel:'chrome',headless:true});
  try {
    fs.mkdirSync('tmp/brand-colours',{recursive:true});
    const context=await browser.newContext({reducedMotion:'reduce',viewport:{width:1440,height:1000}});
    const page=await context.newPage(),home=await context.newPage(),errors=[];
    page.on('pageerror',e=>errors.push(e.message));home.on('pageerror',e=>errors.push(e.message));
    await home.goto(base);await home.waitForLoadState('networkidle');
    assert.equal(await cssColour(home,'[data-component="home:3:services"]'),'rgb(36, 58, 83)');
    assert.equal(await cssColour(home,'[data-component="home:4:features"]'),'rgb(40, 26, 44)');
    assert.equal(await cssColour(home,'#home-faq'),'rgb(52, 74, 58)');
    assert.equal(await cssColour(home,'.site-footer'),'rgb(26, 43, 61)');
    assert.equal(await cssColour(home,'.home-hero .button-primary'),'rgb(216, 203, 221)');
    await page.goto(guide);await page.waitForLoadState('networkidle');
    assert.equal(await page.locator('[data-colour-picker]').count(),58);
    const values=await page.locator('[data-colour-hex]').evaluateAll(els=>els.map(el=>[el.dataset.colourHex,el.value]));
    for(const [id,value] of values)assert.equal(value,defaults[id],id+' supplied hex');
    assert.equal(new Set(values.map(([id])=>id)).size,Object.keys(defaults).length);
    assert.equal(await page.locator('[data-contrast-pair="paper ocean-800"] [data-contrast-ratio]').textContent(),contrast('#FFFFFF','#243A53').toFixed(2)+':1');
    for(const width of [1440,768,390,320]) {
      await page.setViewportSize({width,height:1000});
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'guideline overflow '+width);
      assert(await page.locator('[data-colour-hex]').evaluateAll(els=>els.every(el=>el.getBoundingClientRect().width>40)),'usable inputs '+width);
      await page.locator('[data-brand-editor]').evaluate(el=>scrollTo({top:el.getBoundingClientRect().top+scrollY-90,behavior:'instant'}));
      if([1440,390].includes(width))await page.screenshot({path:`tmp/brand-colours/guidelines-${width}.png`});
    }
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('[data-colour-picker="ocean-800"]').first().fill('#8b3d57');
    await home.waitForFunction(()=>getComputedStyle(document.querySelector('[data-component="home:3:services"]')).backgroundColor==='rgb(139, 61, 87)');
    assert.equal(await cssColour(home,'.site-header .site-nav>.site-nav-link:last-of-type'),'rgb(139, 61, 87)');
    assert((await page.locator('[data-colour-hex="ocean-800"]').evaluateAll(els=>els.map(el=>el.value))).every(v=>v==='#8B3D57'),'linked primary, scale and Information update together');
    await page.locator('[data-colour-hex="forest-800"]').first().fill('#405B37');
    await page.locator('[data-colour-hex="forest-800"]').first().blur();
    await home.waitForFunction(()=>getComputedStyle(document.querySelector('#home-faq')).backgroundColor==='rgb(64, 91, 55)');
    await page.locator('[data-colour-hex="paper"]').first().fill('#FFFBE9');
    await page.locator('[data-colour-hex="paper"]').first().blur();
    await home.waitForFunction(()=>getComputedStyle(document.querySelector('[data-component="home:7:cta"]')).backgroundColor==='rgb(255, 251, 233)');
    await page.getByRole('link',{name:'View homepage',exact:true}).click();await page.waitForLoadState('networkidle');
    assert.equal(await cssColour(page,'[data-component="home:3:services"]'),'rgb(139, 61, 87)','preview persists after navigation');
    await page.reload();await page.waitForLoadState('networkidle');
    assert.equal(await cssColour(page,'#home-faq'),'rgb(64, 91, 55)','preview persists after reload');
    const fresh=await browser.newContext({reducedMotion:'reduce'}),visitor=await fresh.newPage();
    await visitor.goto(base);await visitor.waitForLoadState('networkidle');
    assert.equal(await cssColour(visitor,'[data-component="home:3:services"]'),'rgb(36, 58, 83)','preview is not published to other visitors');
    await fresh.close();
    await page.goto(guide);await page.waitForLoadState('networkidle');
    const field=page.locator('[data-colour-hex="ocean-800"]').first();
    await field.fill('#GGGGGG');await field.blur();
    assert.equal(await field.getAttribute('aria-invalid'),'true');
    assert.equal(await cssColour(home,'[data-component="home:3:services"]'),'rgb(139, 61, 87)','invalid input cannot overwrite a valid preview');
    await page.locator('[data-colour-reset="ocean-800"]').first().click();
    await home.waitForFunction(()=>getComputedStyle(document.querySelector('[data-component="home:3:services"]')).backgroundColor==='rgb(36, 58, 83)');
    assert.equal(await cssColour(home,'#home-faq'),'rgb(64, 91, 55)','reset one leaves other previews intact');
    await page.getByRole('button',{name:'Reset preview',exact:true}).click();
    await home.waitForFunction(()=>getComputedStyle(document.querySelector('#home-faq')).backgroundColor==='rgb(52, 74, 58)');
    assert.equal(await page.evaluate(key=>localStorage.getItem(key),brandStorageKey),null);
    assert.equal(await cssColour(home,'[data-component="home:7:cta"]'),'rgb(255, 255, 255)');
    await context.grantPermissions(['clipboard-read','clipboard-write']);
    await page.getByRole('button',{name:'Copy CSS tokens',exact:true}).click();
    const copied=await page.evaluate(()=>navigator.clipboard.readText());
    assert(copied.includes('--brand-ocean-800: #243A53;'));
    assert(copied.includes('--brand-error: #B74855;'));
    const primary=home.locator('[data-component="home:7:cta"] [data-button-style="primary"]');
    await primary.hover();await home.waitForTimeout(220);
    assert.equal(await primary.evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(63, 91, 120)');
    await primary.evaluate(el=>el.addEventListener('click',event=>event.preventDefault(),{once:true}));
    await home.mouse.down();
    await home.waitForTimeout(220);
    assert.equal(await primary.evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(26, 43, 61)');
    await home.mouse.up();
    await home.emulateMedia({colorScheme:'dark'});
    await home.evaluate(()=>{document.documentElement.dataset.theme='dark'});
    await home.waitForFunction(()=>getComputedStyle(document.body).backgroundColor==='rgb(26, 43, 61)');
    assert.equal(await cssColour(home,'body'),'rgb(26, 43, 61)');
    assert.equal(await cssColour(home,'.site-header'),'rgb(26, 43, 61)');
    assert.equal(await cssColour(home,'[data-component="home:4:features"]'),'rgb(40, 26, 44)');
    // Corrupt or unavailable browser storage must not break the public site.
    const corrupt=await browser.newContext();await corrupt.addInitScript(()=>{localStorage.setItem('hoea-brand-colours-v1','{broken')});
    const invalid=await corrupt.newPage();await invalid.goto(base);await invalid.waitForLoadState('networkidle');
    assert.equal(await cssColour(invalid,'#home-faq'),'rgb(52, 74, 58)');await corrupt.close();
    assert.deepEqual(errors,[]);
    await context.close();
    console.log('PASS: all supplied swatches, exact section colours, responsive editor, linked edits, cross-tab sync, navigation/reload persistence, invalid-input protection, individual/global reset, isolated browser preview and dark mode.');
  } finally {await browser.close();server.close();}
})().catch(error=>{console.error(error);process.exitCode=1});
